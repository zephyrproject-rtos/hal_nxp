/*! @name CTRL1 - Control Register CTRL */
/*! @{ */

#define PMRO_CTRL1_EN_MASK                       (0x3FFFFU)
#define PMRO_CTRL1_EN_SHIFT                      (0U)
/*! EN - 18 Dut Ring Oscillator enable */
#define PMRO_CTRL1_EN(x)                         (((uint32_t)(((uint32_t)(x)) << PMRO_CTRL1_EN_SHIFT)) & PMRO_CTRL1_EN_MASK)

