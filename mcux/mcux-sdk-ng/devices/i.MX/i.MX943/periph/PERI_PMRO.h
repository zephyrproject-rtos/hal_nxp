#define PMRO_CTRL1_DIV_SHIFT                     (24U)
/*! DIV - Programmable Divider bits
 *  0b000..Divide by 1
 *  0b001..Divide by 2
 *  0b010..Divide by 4
 *  0b011..Divide by 8
 *  0b100..Divide by 16
 *  0b101..Divide by 32
 *  0b110..Divide by 64
 *  0b111..Divide by 128
 */
#define PMRO_CTRL1_DIV(x)                        (((uint32_t)(((uint32_t)(x)) << PMRO_CTRL1_DIV_SHIFT)) & PMRO_CTRL1_DIV_MASK)
/*! @} */

